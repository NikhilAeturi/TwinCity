                      border: isPickingStagePos ? '1px solid #38bdf8' : '1px solid rgba(255, 255, 255, 0.12)',
                      background: isPickingStagePos ? 'linear-gradient(135deg, #0284c7 0%, #06b6d4 100%)' : 'rgba(255, 255, 255, 0.06)',
                      color: '#ffffff',
                      fontWeight: 700,
                      fontSize: '0.72rem',
